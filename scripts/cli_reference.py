"""Command line reference of the website, generated from artisan.

Reads the output of ``php artisan list --format=json`` and writes
website/src/content/docs/reference/cli.md (English) and its German twin
de/reference/cli.md. Only the ``tesserarr:*`` commands are listed, without the
test-only ``tesserarr:test:*`` ones and without the options every command has
(``--help``, ``--quiet`` ...): the framework's own commands change with every
Laravel update and would turn the freshness check red without a change here.

CI regenerates both pages and fails when they differ from the committed ones
(.github/workflows/ci.yml, "CLI reference is up to date"). The descriptions come
from the command classes in app/Console/Commands and stay English on both pages.

Standard library only. Values from the listing are data: printed, never run.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "website" / "src" / "content" / "docs"

# Options of every Symfony/Laravel command; they say nothing about a command.
STANDARD_OPTIONS = {"help", "silent", "quiet", "verbose", "version", "ansi", "no-ansi", "no-interaction", "env"}

TEXT = {
    "en": {
        "title": "Command line",
        "description": "Every tesserarr command of artisan, with its arguments and options.",
        "comment": (
            "This page is generated by `scripts/cli_reference.py` from `php artisan list --format=json`; "
            "change the descriptions in `app/Console/Commands/`, not here."
        ),
        "intro": (
            "Run a command with the image's `artisan` entry point, for example "
            "`docker compose run --rm --no-deps web artisan list tesserarr`."
        ),
        "none": "No `tesserarr` command yet.",
        "usage": "Usage",
        "arguments": "Arguments",
        "options": "Options",
        "argument": "Argument",
        "required": "Required",
        "option": "Option",
        "meaning": "Description",
        "default": "Default",
        "yes": "yes",
        "no": "no",
    },
    "de": {
        "title": "Befehlszeile",
        "description": "Jeder tesserarr-Befehl von artisan, mit seinen Argumenten und Optionen.",
        "comment": (
            "Diese Seite wird von `scripts/cli_reference.py` aus `php artisan list --format=json` erzeugt; "
            "ändere die Beschreibungen in `app/Console/Commands/`, nicht hier."
        ),
        "intro": (
            "Führe einen Befehl über den Einstiegspunkt `artisan` des Images aus, zum Beispiel "
            "`docker compose run --rm --no-deps web artisan list tesserarr`. "
            "Die Beschreibungen stammen aus dem Code und sind englisch."
        ),
        "none": "Noch kein `tesserarr`-Befehl.",
        "usage": "Aufruf",
        "arguments": "Argumente",
        "options": "Optionen",
        "argument": "Argument",
        "required": "Pflicht",
        "option": "Option",
        "meaning": "Beschreibung",
        "default": "Standard",
        "yes": "ja",
        "no": "nein",
    },
}


def tesserarr_commands(listing: dict[str, Any]) -> list[dict[str, Any]]:
    commands = [
        c
        for c in listing.get("commands", [])
        if isinstance(c, dict)
        and str(c.get("name", "")).startswith("tesserarr:")
        and not str(c.get("name", "")).startswith("tesserarr:test:")
        and not c.get("hidden", False)
    ]
    return sorted(commands, key=lambda c: str(c["name"]))


def _cell(value: Any) -> str:
    text = re.sub(r"</?[a-z-]+>", "", str(value))  # console colour tags
    return " ".join(text.split()).replace("|", "\\|")


def _default(value: Any) -> str:
    if value is None or value is False or value == [] or value == "":
        return ""
    return f"`{_cell(json.dumps(value) if not isinstance(value, str) else value)}`"


def _definition_items(definition: Any, key: str) -> list[dict[str, Any]]:
    items = definition.get(key, {}) if isinstance(definition, dict) else {}
    if isinstance(items, dict):
        return [v for v in items.values() if isinstance(v, dict)]
    return [v for v in items if isinstance(v, dict)] if isinstance(items, list) else []


def render(listing: dict[str, Any], lang: str) -> str:
    t = TEXT[lang]
    lines = [
        "---",
        f"title: {t['title']}",
        f"description: {t['description']}",
        "---",
        "",
        f"<!-- {t['comment']} -->",
        "",
        t["intro"],
        "",
    ]
    commands = tesserarr_commands(listing)
    if not commands:
        lines += [t["none"], ""]
    for command in commands:
        lines += [f"## `{command['name']}`", "", _cell(command.get("description", "")), ""]
        usage = [u for u in command.get("usage", []) if isinstance(u, str)][:1]
        if usage:
            lines += [f"### {t['usage']}", "", "```text", usage[0], "```", ""]
        definition = command.get("definition", {})
        arguments = _definition_items(definition, "arguments")
        if arguments:
            lines += [
                f"### {t['arguments']}",
                "",
                f"| {t['argument']} | {t['required']} | {t['meaning']} |",
                "| --- | --- | --- |",
            ]
            for arg in arguments:
                required = t["yes"] if arg.get("is_required") else t["no"]
                lines.append(f"| `{_cell(arg.get('name', ''))}` | {required} | {_cell(arg.get('description', ''))} |")
            lines.append("")
        options = [
            o for o in _definition_items(definition, "options") if str(o.get("name", "")).lstrip("-") not in STANDARD_OPTIONS
        ]
        if options:
            lines += [
                f"### {t['options']}",
                "",
                f"| {t['option']} | {t['meaning']} | {t['default']} |",
                "| --- | --- | --- |",
            ]
            for opt in options:
                lines.append(
                    f"| `{_cell(opt.get('name', ''))}` | {_cell(opt.get('description', ''))} | {_default(opt.get('default'))} |"
                )
            lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("listing", type=Path, help="output of `php artisan list --format=json`")
    parser.add_argument("--docs", type=Path, default=DOCS, help="the website's docs root (tests)")
    args = parser.parse_args(argv)

    try:
        listing = json.loads(args.listing.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        print(f"::error::{args.listing}: not JSON or not readable ({exc})", file=sys.stderr)
        return 1

    for lang, rel in (("en", "reference/cli.md"), ("de", "de/reference/cli.md")):
        target = args.docs / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(render(listing, lang), encoding="utf-8")
        print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
